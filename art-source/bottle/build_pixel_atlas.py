"""Bake unchanged Lua sprite pixels for nvgCreateImage(..., NVG_IMAGE_NEAREST).

Run: python art-source/bottle/build_pixel_atlas.py [--check]
Requires lupa (Lua 5.4); PNG encoding uses only the Python standard library.
Rebuild after editing ItemSprites, ExtraSprites or RelicSprites. Unknown or
changed sprites automatically keep their rectangle renderer until rebuilt.
"""
import argparse
import math
from pathlib import Path
import struct
import sys
import zlib

ROOT = Path(__file__).resolve().parents[2]
# Also accept this workspace's existing isolated Lua validation installation.
if (ROOT / ".tmp/lua-check").is_dir():
    sys.path.insert(0, str(ROOT / ".tmp/lua-check"))
from lupa.lua54 import LuaRuntime


def source_sprites():
    lua = LuaRuntime(unpack_returned_tuples=True)
    lua.globals().package.path = (ROOT / "scripts/?.lua").as_posix() + ";" + lua.globals().package.path
    lua.execute("""
        package.loaded['Machine.Palette']={}
        package.loaded['Bottle.PixelAtlasData']={}
        local art=require('Bottle.Art')
        local function pool(fn,name)
            for i=1,100 do
                local key,value=debug.getupvalue(fn,i)
                if key==name then return value end
                if not key then break end
            end
            error('sprite pool not found: '..name)
        end
        items=pool(art.Item,'SPRITES');relics=pool(art.Relic,'RELIC_SPRITES')
        fingerprint=require('Bottle.PixelCache').Fingerprint
    """)
    result = []
    for category in ("items", "relics"):
        result.extend((category, name, sprite) for name, sprite in lua.globals()[category].items())
    return lua, sorted(result, key=lambda value: value[:2])


def pixels(sprite, cooling):
    data = bytearray(sprite.width * sprite.height * 4)
    for _, group in sprite.groups.items():
        c = group.color
        color = [c[1], c[2], c[3], c[4] if c[4] is not None else 255]
        assert color[3] == 255, "Translucent source art needs explicit compositing support"
        if cooling:
            gray = math.floor((color[0] * .2126 + color[1] * .7152 + color[2] * .0722) * .78)
            color[:3] = [gray] * 3
        rects = group.rects
        for i in range(1, len(rects) + 1, 4):
            x, y, w, h = (rects[i + j] for j in range(4))
            assert x >= 0 and y >= 0 and x + w <= sprite.width and y + h <= sprite.height
            for row in range(y, y + h):
                start = (row * sprite.width + x) * 4
                data[start:start + w * 4] = bytes(color) * w
    return bytes(data)


def png(width, height, data):
    def chunk(kind, payload):
        return struct.pack(">I", len(payload)) + kind + payload + struct.pack(">I", zlib.crc32(kind + payload))
    rows = b"".join(b"\0" + data[y * width * 4:(y + 1) * width * 4] for y in range(height))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))


def build():
    lua, sprites = source_sprites()
    width, padding = 512, 2
    x = y = row_height = padding
    entries, tiles = {}, []
    for category, name, sprite in sprites:
        key = lua.globals().fingerprint(sprite)
        normal, cooling = pixels(sprite, False), pixels(sprite, True)
        signature = (sprite.width, sprite.height, normal, cooling)
        if key in entries:
            assert entries[key][1] == signature, "Sprite fingerprint collision"
            continue
        region = []
        for tile in (normal, cooling):
            if x + sprite.width + padding > width:
                x, y, row_height = padding, y + row_height + padding, 0
            region.extend((x, y))
            tiles.append((x, y, sprite.width, sprite.height, tile))
            x += sprite.width + padding
            row_height = max(row_height, sprite.height)
        # x,y,width,height,coolingX,coolingY; transparent padding prevents bleed.
        rect = (region[0], region[1], sprite.width, sprite.height, region[2], region[3])
        entries[key] = (rect, signature, category + ":" + name)
    height = 1 << (y + row_height + padding - 1).bit_length()
    data = bytearray(width * height * 4)
    for tx, ty, tw, th, tile in tiles:
        for row in range(th):
            start = ((ty + row) * width + tx) * 4
            data[start:start + tw * 4] = tile[row * tw * 4:(row + 1) * tw * 4]
    lines = ["-- Generated by art-source/bottle/build_pixel_atlas.py; do not edit.",
             "return {", '    path="image/bottle/pixel-icons.png",',
             f"    width={width},height={height},", "    regions={"]
    for key, (rect, _, name) in sorted(entries.items()):
        lines.append('        ["' + key + '"]={' + ",".join(map(str, rect)) + "}, -- " + name)
    lines.extend(("    }", "}", ""))
    return {ROOT / "assets/image/bottle/pixel-icons.png": png(width, height, data),
            ROOT / "scripts/Bottle/PixelAtlasData.lua": "\n".join(lines).encode()}, len(sprites), len(entries), width, height


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated files without writing")
    args = parser.parse_args()
    outputs, count, unique, width, height = build()
    for path, content in outputs.items():
        if args.check:
            assert path.read_bytes() == content, f"Rebuild stale atlas: {path}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(f"{'Verified' if args.check else 'Baked'} {count} sprites, {unique * 2} variants, {width}x{height}, nearest image flag required")
